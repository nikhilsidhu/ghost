//! Writes the TypeScript types the front end uses for command results and events,
//! from the Rust types the backend actually sends, into `src/lib/generated/`.
//! `cargo test -p ghost-app bindings` regenerates them; CI fails if the committed
//! files differ, so the two sides cannot drift apart.

use std::path::PathBuf;

use ts_rs::{Config, TS};

use crate::dto::*;
use crate::error::{CommandError, ErrorCode};
use crate::relay_task::{
    ChannelWaitingEvent, ConnectivityDto, LiveStateDto,
    OnlinePresenceEvent, OnlinePresenceMemberDto, VoiceChannelMember, VoiceChannelMembersEvent, VoiceMuteStateEvent,
    VoiceParticipantsEvent, VoiceQualityEvent, VoiceSpeakingEvent, VoiceStateEvent,
};

fn out_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/lib/generated")
}

fn config() -> Config {
    // Serde writes 64-bit integers as JSON numbers; every one Ghost sends fits exactly.
    Config::new().with_large_int("number").with_out_dir(out_dir())
}

/// The constants the front end shares with the backend, which ts-rs does not export:
/// the permission bits of a server policy and the message types a channel's history
/// holds. Written beside the generated types, from the same Rust values.
#[test]
fn export_typescript_constants() {
    use ghost_core::crypto::MessageType;
    use ghost_wire::policy::{ALL_PERMISSIONS, INVITE, KICK, MANAGE_CHANNELS, MANAGE_ROLES};
    let source = format!(
        "// Written by `cargo test -p ghost-app bindings` from the Rust constants; see src-tauri/src/bindings.rs. Do not edit this file manually.\n\
         \n\
         /** Permission bits of a server policy. */\n\
         export const PERMISSIONS = {{\n  invite: {INVITE},\n  kick: {KICK},\n  manageChannels: {MANAGE_CHANNELS},\n  manageRoles: {MANAGE_ROLES},\n}} as const;\n\
         export const ALL_PERMISSIONS = {ALL_PERMISSIONS};\n\
         \n\
         /** Message types a channel's history holds. */\n\
         export const MESSAGE_TYPES = {{\n  text: {text},\n  delete: {delete},\n  metadata: {metadata},\n  undecryptable: {undecryptable},\n  historyGap: {history_gap},\n}} as const;\n\
         \n\
         /** How long a pairing session lives on the relay, in milliseconds; the existing device waits no longer. */\n\
         export const PAIRING_TTL_MS = {pairing_ttl};\n",
        pairing_ttl = ghost_wire::PAIRING_TTL_MS,
        text = MessageType::Text as u8,
        delete = MessageType::Delete as u8,
        metadata = MessageType::Metadata as u8,
        undecryptable = MessageType::Undecryptable as u8,
        history_gap = MessageType::HistoryGap as u8,
    );
    std::fs::write(out_dir().join("constants.ts"), source).unwrap();
}

